#!/usr/bin/env python3
"""Fail-closed, same-run A->B native-model-output handoff *lab* for Genesis #162.

A runs a pinned native model on public text. B is a different GitHub-hosted
worker and actually reads the bounded generated bytes from a one-day artifact.
This is neither a production resident handoff nor scientific admission.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

SCHEMA = "janus.nexus.same_run_native_output_handoff.v1"
MODEL_COMMIT = "c8c890206f53591d6bfe444d103ed5dd07ec2296"
CHECKPOINT_SHA256 = "fc767adb812ac3bea54c44cbccfa9680941f95e2c8a77120559b41da044d9463"
PROMPT = "JANUS NEXUS LAB 41054190160: give a short non-authoritative research status."
SHA40 = re.compile(r"^[a-f0-9]{40}$")
RUN = re.compile(r"^[1-9][0-9]{3,23}$")
MAX_BYTES = 15_000


class Hold(Exception):
    pass


def require(condition: bool, code: str) -> None:
    if not condition:
        raise Hold(code)


def digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def bounded_bytes(path: Path, limit: int = MAX_BYTES) -> bytes:
    require(path.is_file() and not path.is_symlink(), "INPUT_MISSING_OR_SYMLINK")
    require(path.stat().st_size > 0 and path.stat().st_size <= limit,
            "INPUT_SIZE_OUT_OF_BOUNDS")
    return path.read_bytes()


def read_receipt(path: Path) -> dict:
    value = json.loads(bounded_bytes(path, 65_536))
    require(isinstance(value, dict), "RECEIPT_NOT_OBJECT")
    return value


def save_receipt(path: Path, value: dict) -> None:
    require(not path.is_symlink() and not path.exists(), "RECEIPT_ALREADY_EXISTS")
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("x", encoding="utf-8") as handle:
        json.dump(value, handle, sort_keys=True, indent=2)
        handle.write("\n")


def validate_identity(run_id: str, attempt: int, source_sha: str) -> None:
    require(bool(RUN.fullmatch(run_id)), "RUN_ID_INVALID")
    require(type(attempt) is int and 1 <= attempt <= 1000, "RUN_ATTEMPT_INVALID")
    require(bool(SHA40.fullmatch(source_sha)), "SOURCE_SHA_INVALID")


def suffix_from_output(raw: bytes) -> str:
    require(0 < len(raw) <= MAX_BYTES, "OUTPUT_SIZE_OUT_OF_BOUNDS")
    try:
        value = raw.decode("utf-8")
    except UnicodeError as exc:
        raise Hold("OUTPUT_NOT_UTF8") from exc
    require(value.startswith(PROMPT), "MODEL_PROMPT_PREFIX_MISMATCH")
    # The CLI prints precisely one additional terminal newline.
    value = value[:-1] if value.endswith("\n") else value
    suffix = value[len(PROMPT):]
    require(bool(suffix.strip()), "GENERATED_SUFFIX_EMPTY")
    return suffix


def verify_model_source(brain: Path) -> None:
    require(brain.is_dir() and not brain.is_symlink(), "MODEL_SOURCE_UNAVAILABLE")
    try:
        actual_commit = subprocess.check_output(
            ["git", "-C", str(brain), "rev-parse", "HEAD"],
            text=True, stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.SubprocessError) as exc:
        raise Hold("MODEL_GIT_PROVENANCE_UNAVAILABLE") from exc
    require(actual_commit == MODEL_COMMIT, "MODEL_GIT_COMMIT_DRIFT")
    file = brain / "janus_model/checkpoints/promoted.pt"
    require(file.is_file() and not file.is_symlink(), "MODEL_CHECKPOINT_MISSING")
    h = hashlib.sha256()
    with file.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(chunk)
    require(h.hexdigest() == CHECKPOINT_SHA256, "MODEL_CHECKPOINT_DIGEST_MISMATCH")
    state = read_receipt(brain / "janus_model/state/JANUS_MODEL_STATE.json")
    require(state.get("checkpoint_sha256") == CHECKPOINT_SHA256,
            "MODEL_STATE_CHECKPOINT_MISMATCH")


def phase_a(raw: bytes, run_id: str, attempt: int, source_sha: str) -> dict:
    validate_identity(run_id, attempt, source_sha)
    suffix = suffix_from_output(raw)
    encoded = suffix.encode("utf-8")
    return {
        "schema": SCHEMA + ".worker_a",
        "status": "PRODUCED_NATIVE_OUTPUT_FOR_SCOPED_LAB_ONLY",
        "run_id": run_id,
        "run_attempt": attempt,
        "genesis_source_sha": source_sha,
        "native_model_commit": MODEL_COMMIT,
        "native_checkpoint_sha256": CHECKPOINT_SHA256,
        "output_sha256": digest(raw),
        "output_bytes": len(raw),
        "generated_suffix_sha256": digest(encoded),
        "generated_suffix_bytes": len(encoded),
        "raw_output_short_lived_transfer": True,
        "model_quality_verified": False,
        "model_output_is_authority": False,
        "source_writeback": False,
        "external_effect": False,
        "authority_delta": 0,
    }


def phase_b(a: dict, raw: bytes, run_id: str, attempt: int,
            source_sha: str) -> dict:
    require(a == phase_a(raw, run_id, attempt, source_sha),
            "WORKER_A_RECEIPT_MISMATCH")
    suffix = suffix_from_output(raw)
    words = suffix.split()
    # B *consumes* the raw A output and computes these values independently.
    # It does not execute any instruction contained in the model output.
    candidate = {
        "untrusted_generated_suffix_sha256": digest(suffix.encode("utf-8")),
        "untrusted_word_count": len(words),
        "untrusted_question_marks": suffix.count("?"),
        "candidate_admission": "HOLD_UNEVALUATED_MODEL_PROPOSAL",
    }
    return {
        "schema": SCHEMA + ".worker_b",
        "status": "PASS_SCOPED_ACTUAL_MODEL_BYTES_CONSUMED_BY_NEW_WORKER",
        "run_id": run_id,
        "run_attempt": attempt,
        "genesis_source_sha": source_sha,
        "worker_a_receipt_sha256": digest(json.dumps(
            a, sort_keys=True, separators=(",", ":")).encode("utf-8")),
        "consumed_output_sha256": digest(raw),
        "candidate": candidate,
        "production_model_output_loaded": False,
        "production_receiver_ack": False,
        "real44_same_run_materialized": False,
        "full_issue_162_acceptance": False,
        "source_writeback": False,
        "external_effect": False,
        "authority_delta": 0,
    }


def verdict(a: dict, b: dict, raw: bytes, run_id: str, attempt: int,
            source_sha: str) -> dict:
    require(b == phase_b(a, raw, run_id, attempt, source_sha),
            "WORKER_B_RECEIPT_MISMATCH")
    return {
        "schema": SCHEMA + ".independent_verdict",
        "status": "PASS_SCOPED_SAME_RUN_MODEL_OUTPUT_HANDOFF_LAB_ONLY",
        "run_id": run_id,
        "run_attempt": attempt,
        "worker_a_output_sha256": a["output_sha256"],
        "worker_b_consumed_sha256": b["consumed_output_sha256"],
        "same_run_model_bytes_consumed": True,
        "same_run_g1_g20": False,
        "lease_race_resolved": False,
        "durable_production_handoff": False,
        "full_issue_162_acceptance": False,
        "source_writeback": False,
        "authority_delta": 0,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("phase", choices=("produce", "consume", "verify"))
    parser.add_argument("--raw", type=Path, required=True)
    parser.add_argument("--brain", type=Path, required=True)
    parser.add_argument("--a", type=Path)
    parser.add_argument("--b", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--attempt", type=int, required=True)
    parser.add_argument("--source-sha", required=True)
    args = parser.parse_args()
    try:
        verify_model_source(args.brain)
        raw = bounded_bytes(args.raw)
        if args.phase == "produce":
            report = phase_a(raw, args.run_id, args.attempt, args.source_sha)
        else:
            require(args.a is not None, "WORKER_A_RECEIPT_REQUIRED")
            a = read_receipt(args.a)
            if args.phase == "consume":
                report = phase_b(a, raw, args.run_id, args.attempt, args.source_sha)
            else:
                require(args.b is not None, "WORKER_B_RECEIPT_REQUIRED")
                report = verdict(a, read_receipt(args.b), raw, args.run_id,
                                 args.attempt, args.source_sha)
        save_receipt(args.out, report)
        print("NEXUS_NATIVE_HANDOFF=" + report["status"])
        return 0
    except (Hold, OSError, ValueError, UnicodeError, json.JSONDecodeError) as exc:
        code = str(exc) if isinstance(exc, Hold) else "HANDOFF_INPUT_UNVERIFIED"
        print("NEXUS_NATIVE_HANDOFF=HOLD:" + code, file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
